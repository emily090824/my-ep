// Encrypts the private persona pages so they can be published without being readable.
//
//   node tools/lock.mjs <password>
//
// Reads every private/<slug>.json (git-ignored, never published) and writes js/locked.js,
// which holds only ciphertext. The site decrypts a page in the visitor's browser when they
// enter the password (or arrive with ?intro=<password> in the link).
// AES-256-GCM with a key derived from the password by PBKDF2-SHA-256.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { webcrypto as crypto } from "node:crypto";

const password = process.argv[2];
if (!password) { console.error("usage: node tools/lock.mjs <password>"); process.exit(1); }
const ITER = 250000;
const b64 = (u8) => Buffer.from(u8).toString("base64");

const out = {};
for (const file of readdirSync("private").filter((f) => f.endsWith(".json"))) {
  const slug = file.replace(/\.json$/, "");
  const plain = new TextEncoder().encode(JSON.stringify(JSON.parse(readFileSync(`private/${file}`, "utf8"))));
  const salt = crypto.getRandomValues(new Uint8Array(16)), iv = crypto.getRandomValues(new Uint8Array(12));
  const base = await crypto.subtle.importKey("raw", new TextEncoder().encode(password), "PBKDF2", false, ["deriveKey"]);
  const key = await crypto.subtle.deriveKey({ name: "PBKDF2", salt, iterations: ITER, hash: "SHA-256" }, base,
    { name: "AES-GCM", length: 256 }, false, ["encrypt"]);
  const data = new Uint8Array(await crypto.subtle.encrypt({ name: "AES-GCM", iv }, key, plain));
  out[slug] = { iter: ITER, salt: b64(salt), iv: b64(iv), data: b64(data) };
  console.log("locked", slug);
}
writeFileSync("js/locked.js",
  "/* Generated by tools/lock.mjs — encrypted persona pages. Do not edit by hand. */\n" +
  "window.LOCKED = " + JSON.stringify(out, null, 2) + ";\n");
